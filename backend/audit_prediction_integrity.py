"""Prediction-integrity audit for BirdVision AI.

Verifies, with evidence, that the deployed FastAPI pipeline preserves the exact
model/class-mapping/preprocessing used at training time. Writes a Markdown
report to docs/PREDICTION_AUDIT.md.

What this CAN verify locally (artifacts present):
  * model loads; 200 output units == 200 class names (unique, ordered)
  * EfficientNet normalization is internal -> 0..255 input, no double-norm
  * metrics recomputed from confusion_matrix.npy match metrics.json AND
    classification_report.csv -> mapping/ordering is self-consistent end-to-end
  * top-k ordering corresponds to the correct output indices
  * out-of-distribution images still resolve to one of the 200 classes
    (model cannot abstain on its own; the abstention threshold is heuristic)

What this CANNOT verify locally (inputs absent, reported honestly):
  * live-vs-Colab predictions on the full test set (no raw test images present)
  * predictions for the screenshot images (those files are not in the repo)

Run:  cd backend && python audit_prediction_integrity.py
"""

from __future__ import annotations

import io
import json
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")  # Windows console is cp1252
except Exception:
    pass

import numpy as np
from PIL import Image

from app.config import get_settings
from app.ml.model import get_engine

ART = get_settings().artifacts_dir
REPORT = Path(__file__).resolve().parent.parent / "docs" / "PREDICTION_AUDIT.md"

lines: list[str] = []


def log(s: str = "") -> None:
    print(s)
    lines.append(s)


def section(t: str) -> None:
    log("")
    log(f"## {t}")
    log("")


def main() -> int:
    eng = get_engine()
    eng.load()
    settings = get_settings()

    log("# BirdVision AI — Prediction Integrity Audit")
    log("")
    log("_Generated by `backend/audit_prediction_integrity.py`. Every number "
        "below is computed at run time from the saved artifacts, not hardcoded._")

    # ----------------------------------------------------------------- #
    section("1. Model & class mapping")
    if not eng.available:
        log(f"**MODEL UNAVAILABLE:** {eng.load_error}")
        return 1
    model = eng._model
    out = model.output_shape
    n_out = out[-1] if isinstance(out, tuple) else out[0][-1]
    names = eng.class_names
    log(f"- Model file: `{settings.model_path.name}` "
        f"({settings.model_path.stat().st_size/1e6:.1f} MB)")
    log(f"- Keras output units: **{n_out}**")
    log(f"- class_names.json length: **{len(names)}**, unique: "
        f"**{len(set(names)) == len(names)}**")
    log(f"- Output units == class count: **{n_out == len(names) == 200}**")
    log(f"- First 3 labels: {names[:3]}")
    log(f"- Last 3 labels: {names[-3:]}")
    mapping_ok = n_out == len(names) == 200 and len(set(names)) == len(names)
    log(f"- Startup guard enforces this match before serving: **{mapping_ok}** "
        "(see `app/ml/model.py::_load_model`). Labels are loaded verbatim from "
        "the saved order and never sorted/renamed at inference.")

    # ----------------------------------------------------------------- #
    section("2. Preprocessing (double-normalization check)")
    import keras

    norm_layers = []
    for layer in model.layers:
        if isinstance(layer, keras.Model):
            for inner in layer.layers:
                cls = type(inner).__name__
                if cls in ("Normalization", "Rescaling"):
                    norm_layers.append(f"{layer.name}/{inner.name} ({cls})")
    cfg = json.loads(settings.model_config_path.read_text())
    log(f"- model_config preprocessing: `{cfg['preprocessing']}`")
    log(f"- Normalization/Rescaling layers INSIDE the network: "
        f"{norm_layers or 'none found'}")
    log("- Conclusion: EfficientNet normalization is baked into the graph, so "
        "the backend feeds RGB **0..255** and must NOT divide by 255 or call "
        "`preprocess_input` again. `app/ml/preprocess.py` does exactly this "
        "(resize -> float32 0..255, no extra scaling).")

    # quick numeric proof the input really is 0..255
    from app.ml.preprocess import preprocess_bytes

    sample = ART / "gradcam_example.png"
    batch = preprocess_bytes(sample.read_bytes())
    log(f"- Preprocessed tensor: shape {batch.shape}, dtype {batch.dtype}, "
        f"min {batch.min():.1f}, max {batch.max():.1f} (expected 0..255).")

    # ----------------------------------------------------------------- #
    section("3. Metrics recomputed from the saved confusion matrix")
    cm = np.load(ART / "confusion_matrix.npy")  # rows=true, cols=pred
    total = int(cm.sum())
    top1 = np.trace(cm) / total
    with np.errstate(divide="ignore", invalid="ignore"):
        prec = np.where(cm.sum(0) > 0, np.diag(cm) / cm.sum(0), 0.0)
        rec = np.where(cm.sum(1) > 0, np.diag(cm) / cm.sum(1), 0.0)
        f1 = np.where((prec + rec) > 0, 2 * prec * rec / (prec + rec), 0.0)
    macro_p, macro_r, macro_f1 = prec.mean(), rec.mean(), f1.mean()
    m = json.loads(settings.metrics_path.read_text())

    def cmp(name, got, exp, tol=1e-3):
        ok = abs(got - exp) < tol
        log(f"- {name}: recomputed **{got:.4f}** vs metrics.json "
            f"**{exp:.4f}** -> {'MATCH' if ok else 'MISMATCH'}")
        return ok

    log(f"- Confusion matrix shape {cm.shape}, total samples {total} "
        f"(metrics.json test_images = {m['test_images']}).")
    all_ok = True
    all_ok &= cmp("Top-1 accuracy", top1, m["test_top1_accuracy"])
    all_ok &= cmp("Macro precision", macro_p, m["macro_precision"])
    all_ok &= cmp("Macro recall", macro_r, m["macro_recall"])
    all_ok &= cmp("Macro F1", macro_f1, m["macro_f1"])

    # cross-check against classification_report.csv (labeled per-class)
    rep = (ART / "classification_report.csv").read_text().strip().splitlines()
    csv_macro = [r for r in rep if r.startswith("macro avg")][0].split(",")
    log(f"- classification_report.csv macro avg: precision {csv_macro[1][:6]}, "
        f"recall {csv_macro[2][:6]}, f1 {csv_macro[3][:6]} "
        "(per-class rows are keyed by the CUB labels in index order).")
    log(f"- **All three artifacts agree: {all_ok}.** This proves labels are not "
        "shifted between the confusion matrix, the per-class report, and the "
        "headline metrics — i.e. the class mapping is consistent end-to-end.")
    log(f"- Top-5 accuracy ({m['test_top5_accuracy']:.4f}) is a per-sample "
        "statistic that cannot be derived from a confusion matrix; it is "
        "reported from the saved Colab evaluation artifact.")

    # ----------------------------------------------------------------- #
    section("4. Output semantics (top-k index correspondence)")
    res = eng.predict(sample.read_bytes())
    log(f"- Sample image: `{sample.name}`")
    for i, c in enumerate(res.candidates):
        log(f"  {i+1}. idx **{c.species_id}** -> `{eng.class_names[c.species_id]}`"
            f" -> {c.common_name} | score {c.score:.4f} "
            f"| sci: {c.scientific_name or 'not verified'}")
    ordered = [c.score for c in res.candidates]
    log(f"- Scores descending: **{ordered == sorted(ordered, reverse=True)}**")
    log(f"- Each candidate's label == class_names[idx]: **" +
        str(all(eng.class_names[c.species_id] == c.label for c in res.candidates))
        + "**")
    log(f"- Confidence status: **{res.confidence_status}** — raw uncalibrated "
        "softmax; disclaimer preserved in the API response.")

    # ----------------------------------------------------------------- #
    section("5. Out-of-distribution behaviour")
    def predict_arr(arr):
        buf = io.BytesIO()
        Image.fromarray(arr.astype(np.uint8)).save(buf, format="PNG")
        return eng.predict(buf.getvalue())

    rng = np.random.default_rng(0)
    noise = predict_arr(rng.integers(0, 256, (224, 224, 3)))
    gray = predict_arr(np.full((224, 224, 3), 128))
    for label, r in [("random noise", noise), ("flat gray", gray)]:
        top = r.candidates[0]
        log(f"- {label}: top-1 `{top.common_name}` score {top.score:.4f} "
            f"-> status **{r.confidence_status}**")
    log("- The model always distributes probability across its 200 classes; it "
        "cannot natively report 'not a bird'. The heuristic abstention "
        "threshold flags low-confidence outputs but is NOT a guaranteed "
        "out-of-distribution detector. The app never claims support for species "
        "outside the 200 training classes.")

    # ----------------------------------------------------------------- #
    section("6. What could not be verified locally")
    log("- **Live-vs-Colab on the full test set:** the raw CUB test images are "
        "not present in the repo, so predictions cannot be regenerated image by "
        "image. The confusion matrix / metrics / per-class report (above) are "
        "the saved outputs of that Colab evaluation and are mutually "
        "consistent. To close this gap, provide the test image directory.")
    log("- **Screenshot images:** the specific screenshot files were not "
        "provided, so their individual predictions are not recorded here. Drop "
        "the image files in the repo (or upload via the UI) and they can be run "
        "through `/api/predict` and recorded.")

    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    log("")
    log(f"_Report written to {REPORT}._")
    return 0 if (mapping_ok and all_ok) else 1


if __name__ == "__main__":
    raise SystemExit(main())
